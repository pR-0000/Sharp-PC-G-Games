def rows_to_ink(rows,start_y=0):
    return {(x,y+start_y) for y,row in enumerate(rows) for x,pixel in enumerate(row) if pixel=='#'}

def default_art():
    frames=[]
    for kind,name in enumerate(NAMES):
        idle=rows_to_ink(STANCES[name]['idle'])
        attack=rows_to_ink(STANCES[name]['attack'])
        run={(min(15,x+1),y) for x,y in idle if y<12}|rows_to_ink(RUN_LEGS[kind],12)
        jump={(x,y) for x,y in idle if y<11}|rows_to_ink(JUMP_LEGS[kind],11)
        hurt={(max(0,x-1) if y<9 else x,y) for x,y in idle}
        guard={(x,min(15,y+1)) for x,y in idle}
        guard|={(x,y) for y in range(16) for x in range(16) if 45<=(x-7.5)**2+(y-7.5)**2<=58}
        frames.extend((idle,run,jump,attack,hurt,guard))
    frames.extend(set(map(tuple,effect)) for effect in EFFECTS)
    assert len(frames)==27 and all(0<=x<16 and 0<=y<16 for frame in frames for x,y in frame)
    return frames

def background(kind):
    return {(x,y) for y,row in enumerate(BACKGROUND_ROWS[kind])
            for x in range(192) if int(row,16)&(1<<x)}

def generate(target='g850'):
    native=target=='g850'
    sizes=range(8 if native else 4,17)
    view_width,view_height=(144,40) if native else (120,21)
    back_width=view_width+48
    path=HERE/'sprites.bmp'
    frames=default_art()
    if not path.exists():write_bmp(path,16,len(frames)*16,[(0,0,0) if (x,y%16) in frames[y//16] else (255,255,255) for y in range(len(frames)*16) for x in range(16)])
    w,h,pixels=read_bmp(path)
    if (w,h)!=(16,432) or any(p not in ((0,0,0),(255,255,255)) for p in pixels):raise ValueError('sprites.bmp: 16 x 432, noir/blanc / black/white')
    frames=[{(x,y) for y in range(16) for x in range(16) if pixels[(i*16+y)*16+x]==(0,0,0)} for i in range(27)]
    lines=['; Generated by assets.py / genere automatiquement.','sprite_directory:']
    directory=[f'sprite_{i}_{n}' for i in range(27) for n in sizes]
    for start in range(0,len(directory),12):lines.append(' dw '+','.join(directory[start:start+12]))
    def data(label,values):
        lines.append(label+':')
        for start in range(0,len(values),24):lines.append(' db '+','.join(str(v) for v in values[start:start+24]))
    for i,frame in enumerate(frames):
        for n in sizes:
            ink={(x,y) for y in range(n) for x in range(n) if (min(15,(2*x+1)*8//n),min(15,(2*y+1)*8//n)) in frame}
            mask=ink|{(x+dx,y+dy) for x,y in ink for dx,dy in ((1,0),(-1,0),(0,1),(0,-1))}
            raw=[]
            for x in range(n):
                for field in (mask,ink):
                    bits=sum(1<<y for y in range(n) if (x,y) in field);raw.extend((bits&255,bits>>8))
            data(f'sprite_{i}_{n}',raw)
    for kind in range(3):
        path=HERE/'backgrounds'/f'arena_{kind+1}.bmp'
        if not path.exists():
            dots=background(kind);write_bmp(path,192,40,[(0,0,0) if (x,y) in dots else (255,255,255) for y in range(40) for x in range(192)])
        w,h,pixels=read_bmp(path)
        if (w,h)!=(192,40):raise ValueError('Background / decor: 192 x 40')
        if native:
            data('background_'+str(kind),[sum(1<<bit for bit in range(8) if sum(pixels[(row*8+bit)*192+x])<384) for row in range(5) for x in range(192)])
        else:
            # Preserve fine outlines with area coverage when shrinking scenery.
            dots={(x,y) for y in range(view_height) for x in range(back_width)
                  if any(sum(pixels[sy*192+sx])<384
                         for sy in range(y*40//view_height,(y+1)*40//view_height)
                         for sx in range(x*192//back_width,(x+1)*192//back_width))}
            data('background_'+str(kind),[sum(1<<bit for bit in range(8) if (x,row*8+bit) in dots)
                                         for row in range(3) for x in range(back_width)])
    data('half_width',[view_width*8//n for n in sizes])
    data('half_height',[view_height*8//n for n in sizes])
    data('tiny_digits',[v<<1 for glyph in ((31,17,31),(0,31,0),(29,21,23),(21,21,31),(7,4,31),(23,21,29),(31,21,29),(1,1,31),(31,21,31),(23,21,31)) for v in glyph])
    data('tiny_heart',[14,28,14])
    destination=HERE if native else HERE/'targets/g80x-32k'
    destination.mkdir(parents=True,exist_ok=True)
    (destination/'generated.inc').write_text('\n'.join(lines)+'\n',encoding='ascii')
    metadata={'characters':list(NAMES),'poses':list(POSES),'sprite_size':[16,16],'atlas':[16,432],
        'order':[f'{name}_{pose}' for name in NAMES for pose in POSES]+['slash','orb','spark'],
        'scales':list(range(8,17)),'black':'lit pixel / point allume'}
    (HERE/'sprites.json').write_text(json.dumps(metadata,indent=2)+'\n',encoding='utf-8')
    preview=[]
    for y in range(448):
        for x in range(256):
            column,row=x//64,y//64
            index=column*6+row if row<6 else 24+column
            dot=index<27 and (x//4%16,y//4%16) in frames[index]
            preview.append((0,34,17) if dot else (170,221,187))
    write_png(HERE/'docs/sprites.png',256,448,preview)
if __name__=='__main__':generate()
