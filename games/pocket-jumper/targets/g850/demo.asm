; A small deterministic driver: look ahead for gaps, blocks and enemies.
demo_controls:
    ld a,JUMP_RIGHT
    ld (input_buttons),a
    ld a,(grounded)
    or a
    ret z
    ld hl,(player_x)
    call fixed_to_int
    ld de,HERO_W+6
    add hl,de
    srl h
    rr l
    srl h
    rr l
    srl h
    rr l
    push hl
    ld b,l
    ld hl,(player_y)
    call fixed_to_int
    ld a,l
    add a,HERO_H
    srl a
    srl a
    srl a
    ld c,a
    call tile_at
    cp 5
    jp z,request_jump
    call is_solid
    pop hl
    jp nc,request_jump
    ld b,l
    ld hl,(player_y)
    call fixed_to_int
    ld a,l
    add a,HERO_H-2
    srl a
    srl a
    srl a
    ld c,a
    call tile_at
    cp 5
    jp z,request_jump
    call is_solid
    jp c,request_jump
    ld ix,enemies
    ld b,4
.enemy:
    ld a,(ix+8)
    or a
    jr z,.next
    ld l,(ix+0)
    ld h,(ix+1)
    push bc
    ld de,(player_x)
    ex de,hl
    call fixed_to_int
    ex de,hl
    or a
    sbc hl,de
    pop bc
    bit 7,h
    jr nz,.next
    ld a,h
    or a
    jr nz,.next
    ld a,l
    cp 28
    jp c,request_jump
.next:
    ld de,9
    add ix,de
    djnz .enemy
    ret
