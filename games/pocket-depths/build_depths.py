def bmp_write(path,art):
    width,height=7,len(art)*9
    stride=(width*3+3)&~3
    pixels=bytearray()
    rows=[line for shape in art for line in shape]
    for row in reversed(rows):
        for c in row: pixels.extend(bytes((0 if c=='1' else 255,))*3)
        pixels.extend(bytes(stride-width*3))
    path.write_bytes(b'BM'+struct.pack('<IHHI',54+len(pixels),0,0,54)+struct.pack('<IiiHHIIiiII',40,width,height,1,24,0,len(pixels),2835,2835,0,0)+pixels)


def bmp_read(path):
    raw=path.read_bytes()
    if len(raw)<54 or raw[:2]!=b'BM': raise ValueError('Invalid BMP / BMP invalide')
    offset=struct.unpack_from('<I',raw,10)[0]
    width,height,planes,bpp,compression=struct.unpack_from('<iiHHI',raw,18)
    if width!=7 or abs(height)!=63 or planes!=1 or bpp!=24 or compression!=0:
        raise ValueError('Atlas: 7 x 63, 24-bit uncompressed / 24 bits sans compression')
    stride=24
    if len(raw)<offset+stride*63: raise ValueError('Truncated BMP / BMP tronque')
    rows=[]
    for y in range(63):
        row=[]
        for x in range(7):
            p=offset+(62-y if height>0 else y)*stride+x*3
            color=raw[p:p+3]
            if color not in (b'\0\0\0',b'\xff\xff\xff'): raise ValueError('Black/white pixels only / Noir et blanc uniquement')
            row.append('1' if color==b'\0\0\0' else '0')
        rows.append(''.join(row))
    return [rows[i*9:(i+1)*9] for i in range(7)]


def ray_steps(index,half=20):
    # Half of forty rays. Other half is mirrored by an offset lookup table.
    slope=((index+0.5)/half)*0.72
    fx=fy=0;tx=0.5/slope;ty=0.5
    entries=[]
    while True:
        if tx<ty:
            distance=tx;tx+=1/slope;fx+=1;side=True
        else:
            distance=ty;ty+=1;fy+=1;side=False
        if distance>=7.875 or fy>7 or fx>7: break
        u=(distance if side else distance*slope)+0.5
        seam=(u%1)<0.09 or (u%1)>0.91
        # bit 6: door centre join; bit 7: jamb. Distance stays in bits 0..5.
        # Left/right mirroring needs no extra table: both features are symmetric.
        centre=abs(u%1-0.5)<min(0.16,0.04*distance)
        visual=min(63,max(4,round(distance*8)))|(0x40 if centre else 0)|(0x80 if seam else 0)
        entries.append((fy*8+fx,visual))
    return entries


def generated(art,native=False):
    width=144 if native else 120
    bits=8 if native else 7
    rows=5 if native else 4
    height=40 if native else 28
    half=width//6
    focal=width*2/3
    lines=['; Generated by build_depths.py / genere automatiquement.']
    def data(label,values):
        lines.append(label+':')
        for i in range(0,len(values),16): lines.append('    db '+','.join(f'${x&255:02X}' for x in values[i:i+16]))
    lines.append('ray_directory:')
    lines.append('    dw '+','.join('ray_'+str(i) for i in range(half)))
    for i in range(half): data('ray_'+str(i),[v for entry in ray_steps(i,half) for v in entry]+[255])
    profiles=[]
    for q in range(64):
        wall_height=round((96 if native else 60)/max(0.5,q/8))
        top=(height-wall_height)//2;bottom=top+wall_height-1
        for row in range(rows):
            fill=outline=0
            for b in range(bits):
                y=row*bits+b
                if top<=y<=bottom:
                    fill|=1<<b
                    if y in (top,bottom) or (y-top)%max(3,round(wall_height/5))==0: outline|=1<<b
            profiles.extend((fill,outline))
    data('wall_profiles',profiles)
    floor=set()
    for z in (2,3):
        y=height//2+round(height*.75/z)
        for x in range(0,width,6): floor.add((x,y))
    for lateral in range(-3,4):
        if not lateral: continue
        for step in range(18,65):
            z=step/8
            x=round(width//2+focal*lateral/z);y=height//2+round(height*.75/z)
            if 0<=x<width and height*.78<=y<height and (x+y)%3: floor.add((x,y))
    lines.append('    IF !BUILD_LITE')
    data('floor_background',[sum(1<<b for b in range(bits) if (x,row*bits+b) in floor) for row in range(2,rows) for x in range(width)])
    lines.append('    ENDIF')
    projection=[]
    for forward in range(8):
        for lateral in range(-8,8):
            x=round(width//2+focal*lateral/max(1,forward))
            projection.append(x if forward and 0<=x<width else 255)
    data('projection_x',projection)
    lines.append('sprite_directory:')
    lines.append('    dw '+','.join(f'sprite_{kind}_{scale}' for kind in range(7) for scale in range(4)))
    for kind,shape in enumerate(art):
        sizes=(((21,30),(11,16),(7,10),(5,7)) if native else ((15,21),(7,10),(5,7),(3,5))) if kind<2 else (((7,10),(7,10),(5,7),(3,5)) if native else ((5,7),(5,7),(3,5),(3,5)))
        unique={}
        for scale,(width,height) in enumerate(sizes):
            if (width,height) in unique:
                lines.append(f'sprite_{kind}_{scale} EQU sprite_{kind}_{unique[(width,height)]}')
                continue
            unique[(width,height)] = scale
            variants = ((False,width,height),)
            if kind<2 and scale==0:
                variants=((True,9,14),(False,width,height))
            for lite,width,height in variants:
                if len(variants)>1: lines.append('    IF BUILD_LITE' if lite else '    ELSE')
                top=((40 if native else 28)-height)//2+(1 if native else 2)
                pixels={(x,top+y) for x in range(width) for y in range(height) if shape[min(8,y*9//height)][min(6,x*7//width)]=='1'}
                mask=pixels|{(x+dx,y+dy) for x,y in pixels for dx,dy in ((1,0),(-1,0),(0,1),(0,-1))}
                bands=[row for row in range(rows) if any((x,row*bits+b) in mask for x in range(width) for b in range(bits))]
                first,last=(min(bands),max(bands)) if bands else (0,0)
                values=[width,first,last-first+1]
                for row in range(first,last+1):
                    for x in range(width):
                        values.extend((sum(1<<b for b in range(bits) if (x,row*bits+b) in mask),sum(1<<b for b in range(bits) if (x,row*bits+b) in pixels)))
                data(f'sprite_{kind}_{scale}',values)
            if len(variants)>1: lines.append('    ENDIF')
    lines.append('    IF BUILD_LITE')
    cells=validate(DEFAULT_SEED)
    data('map_packed',[cells[i]|(cells[i+1]<<4) for i in range(0,256,2)])
    lines.append('    ELSE')
    lines.append('chunk_positions: dw '+','.join(f'world+{y*16+x}' for x,y in ORIGINS))
    shapes=[]
    for chunk in CHUNKS:
        for row in chunk:
            shapes.extend(sum((value==str(kind))<<x for x,value in enumerate(row)) for kind in (1,2))
    data('chunk_shapes',shapes)
    data('level_items',[v for x,y,kind in ITEMS for v in (y*16+x,kind)]+[255])
    lines.append('    ENDIF')
    data('objects',[v for x,y,kind in ITEMS if 4<=kind<=8 for v in (x,y)]+[255])
    data('enemies_template',[v for actor in ACTORS for v in actor])
    data('heart_glyph',[0x06,0x0f,0x1e,0x0f,0x06])
    data('bullet_glyph',[0,0x7c,0x7e,0x7c,0])
    data('weapon_knife',[0,0,0x08,0x1c,0x7e,0x1c,0x08,0,0,0])
    data('weapon_pistol',[0,0,0x60,0x7e,0x42,0x42,0x7e,0x60,0,0])
    data('weapon_shotgun',[0,0,0x7e,0x02,0x7e,0x02,0x7e,0,0,0])
    return '\n'.join(lines)+'\n'


def main():
    parser=Parser('Construire Pocket Depths FR/EN et ses graphismes.','Build Pocket Depths FR/EN and its graphics.')
    parser.add_argument('--assembler',default=os.environ.get('SJASMPLUS','sjasmplus'),help=pick(parser.lang,'Chemin SjASMPlus.','SjASMPlus path.'))
    parser.add_argument('--target',choices=('all','g80x','g850'),default='all')
    args=parser.parse_args()
    assembler=shutil.which(args.assembler)
    if not assembler: parser.error('SjASMPlus: --assembler / SJASMPLUS / PATH')
    if not (HERE/'sprites.bmp').exists(): bmp_write(HERE/'sprites.bmp',ART)
    (HERE/'generated.inc').write_text(generated(bmp_read(HERE/'sprites.bmp')),encoding='ascii')
    (HERE/'targets/g850').mkdir(parents=True,exist_ok=True)
    (HERE/'targets/g850/generated.inc').write_text(generated(bmp_read(HERE/'sprites.bmp'),True),encoding='ascii')
    for native in ((False,True) if args.target=='all' else (args.target=='g850',)):
        build(assembler,native)


def build(assembler,native):
    output=HERE/'build'/('g850' if native else 'g80x');output.mkdir(parents=True,exist_ok=True)
    for seed in range(1,256): validate(seed)
    manifest={'name':'Pocket Depths','version':(HERE/'VERSION').read_text(encoding='utf-8').strip(),'origin':'0100','entry':'0100',
              'target':'Full: PC-G805; Lite: PC-G801/G805','ray_count':48 if native else 40,'visible_cells':7,
              'hud':'Sharp ROM digits plus heart and bullet glyphs','campaign_floors':3,'visible_pixels':[144,40] if native else [120,28],'programs':{}}
    for language,value,lite in (('FR',0,False),('EN',1,False)) + (() if native else (('FR',0,True),('EN',1,True))):
        name=f'depths_{"g850_" if native else "lite_" if lite else ""}{language}'
        base=output/name
        subprocess.run([assembler,'--nologo','--color=off',f'-DBUILD_LANG_EN={value}',f'-DBUILD_LITE={int(lite)}',f'-DTARGET_G850={int(native)}',f'--inc={(ROOT/"lib").as_posix()}',f'--inc={(ROOT/"include").as_posix()}',
                        f'--raw={base.as_posix()}.bin',f'--sym={base.as_posix()}.sym',f'--lst={base.as_posix()}.lst',(HERE/'depths.asm').as_posix()],cwd=HERE,check=True)
        binary=base.with_suffix('.bin').read_bytes();symbols=read_symbols(base.with_suffix('.sym'))
        assert symbols['entry']==0x100 and symbols['program_end']==0x100+len(binary)
        assert symbols['program_end']<=(0x7000 if native else 0x17E3 if lite else 0x7800)
        base.with_suffix('.ihx').write_text(intel_hex(binary,0x100),encoding='ascii')
        end=0xff+len(binary)
        manifest['programs'][name]={'bytes':len(binary),'target':'PC-G850' if native else 'PC-G801/G805' if lite else 'PC-G805','lite':lite,'random_chunks':not lite,'last_address':f'{end:04X}','user_command':f'USER{min(end|255,0x17E2) if lite else end|255:04X}',
            'run_command':'G100','basic_command':'CALL &H100', 'sha256_bin':hashlib.sha256(binary).hexdigest(),
            'sha256_ihx':hashlib.sha256(base.with_suffix('.ihx').read_bytes()).hexdigest()}
        print(f'Pocket Depths {"G850 " if native else "Lite " if lite else "G805 "}{language}: {len(binary)} bytes / octets; USER{min(end|255,0x17E2) if lite else end|255:04X}, G100')
    if native:manifest['target']='PC-G850'
    (output/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')


if __name__=='__main__': main()
