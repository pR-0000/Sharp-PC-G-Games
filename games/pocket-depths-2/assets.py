"""FR/EN: integer tables, sprites and handcrafted level; no ray paths."""
from math import sin, cos, atan, pi
from pathlib import Path

HERE = Path(__file__).resolve().parent
LEVEL = (
    '################',
    '#......#.......#',
    '#..#...#...#...#',
    '#......D.......#',
    '#..#...#...#...#',
    '#......#.......#',
    '###.####...##.##',
    '#......#.......#',
    '#..##..D..##...#',
    '#......#.......#',
    '#..##..####.####',
    '#......#.......#',
    '#......D...#...#',
    '#......#...#...#',
    '#......#.......#',
    '################',
)
# FR: 0 sol, 1 mur, 2 porte, 3 soins, 4 munitions, 5 cle, 6 sortie.
# EN: 0 floor, 1 wall, 2 door, 3 health, 4 ammo, 5 key, 6 exit.
def level_bytes():
    data = bytearray(1 if c == '#' else 2 if c == 'D' else 0 for row in LEVEL for c in row)
    for x, y, tile in ((3,11,4),(5,5,3),(12,8,4),(13,3,5),(2,2,6),(10,13,3)):
        assert data[y*16+x] == 0
        data[y*16+x] = tile
    return data

def generate():
    lines = ['; Generated by assets.py / genere : tables mathematiques uniquement.',
             '; No precomputed ray paths, wall spans or camera views.', 'sin_quarter:']
    values = [round(127*sin(i*pi/128)) for i in range(65)]
    def emit(label, values, word=False):
        lines.append(label + ':')
        for p in range(0,len(values),16):
            lines.append('    '+('dw ' if word else 'db ')+','.join(str(v) for v in values[p:p+16]))
    lines.pop()
    emit('sin_quarter', values)
    emit('delta_quarter', [min(32767, round(256*127/v)) if v else 32767 for v in values],True)
    offsets=[round(atan((i+.5-20)/20)*128/pi) for i in range(40)]
    emit('ray_offsets', [a&255 for a in offsets])
    emit('ray_cosines',[round(255*cos(a*pi/128)) for a in offsets])
    emit('level_initial',level_bytes())
    emit('actors_initial',[4,9,3, 11,5,3, 12,12,3,
                          3,11,4, 5,5,3, 12,8,4, 13,3,5, 2,2,6, 10,13,3])
    # Seven 7-bit columns. Silhouette, eyes, legs / silhouette, yeux, jambes.
    emit('monster_sprite',[0x18,0x7c,0x2e,0x7b,0x2e,0x7c,0x18])
    emit('health_sprite',[0,28,28,127,28,28,0])
    emit('ammo_sprite',[0,124,126,0,124,126,0])
    emit('key_sprite',[14,17,14,4,60,36,0])
    emit('exit_sprite',[127,65,127,8,42,28,8])
    lines.extend(['object_sprites:','    dw health_sprite,ammo_sprite,key_sprite,exit_sprite'])
    emit('heart_icon',[14,31,62,31,14])
    emit('ammo_icon',[0,124,126,124,0])
    emit('key_icon',[6,9,62,8,24])
    emit('compass_fr',list(b'ESON'))
    emit('compass_en',list(b'ESWN'))
    emit('pixel_bits',[1,2,4,8,16,32,64])
    (HERE/'generated.inc').write_text('\n'.join(lines)+'\n',encoding='ascii')

if __name__ == '__main__': generate()
